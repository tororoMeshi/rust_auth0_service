           'registered_web_services'
       );

    IF auth_relation_count = 0 THEN
        EXECUTE $ddl$
            CREATE TABLE public.internal_users (
                internal_user_id integer GENERATED BY DEFAULT AS IDENTITY,
                is_enabled boolean NOT NULL DEFAULT true,
                created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT internal_users_pkey PRIMARY KEY (internal_user_id)
            )
        $ddl$;

        EXECUTE $ddl$
            CREATE TABLE public.external_identities (
                provider text NOT NULL,
                subject text NOT NULL,
                internal_user_id integer NOT NULL,
                linked_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT external_identities_pkey PRIMARY KEY (provider, subject),
                CONSTRAINT external_identities_provider_not_empty CHECK (length(provider) > 0),
                CONSTRAINT external_identities_subject_not_empty CHECK (length(subject) > 0),
                CONSTRAINT external_identities_internal_user_fk
                    FOREIGN KEY (internal_user_id)
                    REFERENCES public.internal_users (internal_user_id)
                    ON DELETE NO ACTION
            )
        $ddl$;

        EXECUTE $ddl$
            CREATE INDEX external_identities_internal_user_id_idx
                ON public.external_identities (internal_user_id)
        $ddl$;

        EXECUTE $ddl$
            CREATE TABLE public.registered_web_services (
                service_id text NOT NULL,
                is_enabled boolean NOT NULL DEFAULT true,
                login_callback_uri text NOT NULL,
                logout_return_uri text NOT NULL,
                service_secret_sha256 bytea NOT NULL,
                created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT registered_web_services_pkey PRIMARY KEY (service_id),
                CONSTRAINT registered_web_services_service_id_format
                    CHECK (service_id ~ '^[a-z0-9][a-z0-9_-]{0,63}$'),
                CONSTRAINT registered_web_services_login_callback_uri_not_empty
                    CHECK (length(login_callback_uri) > 0),
                CONSTRAINT registered_web_services_logout_return_uri_not_empty
                    CHECK (length(logout_return_uri) > 0),
                CONSTRAINT registered_web_services_service_secret_sha256_length
                    CHECK (octet_length(service_secret_sha256) = 32)
            )
        $ddl$;
    END IF;
END
$$;

