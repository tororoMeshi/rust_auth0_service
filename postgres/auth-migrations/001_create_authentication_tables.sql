     WHERE namespace.nspname = 'public'
       AND relation.relname IN (
           'internal_users',
           'external_identities',
           'registered_web_services'
       );

    IF auth_relation_count NOT IN (0, 3) THEN
        RAISE EXCEPTION
            'authentication tables must be all absent or all present; found % of 3',
            auth_relation_count;
    END IF;

    IF auth_relation_count = 3 THEN
        SELECT string_agg(relation.relname, ', ' ORDER BY relation.relname)
          INTO non_table_relations
          FROM pg_class AS relation
          JOIN pg_namespace AS namespace ON namespace.oid = relation.relnamespace
         WHERE namespace.nspname = 'public'
           AND relation.relname IN (
               'internal_users',
               'external_identities',
               'registered_web_services'
           )
